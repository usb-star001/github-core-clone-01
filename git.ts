export const PKT_LINE_MAX = 65520;

export type GitPacket =
  | { kind: 'data'; payload: Buffer; raw: Buffer }
  | { kind: 'flush' }
  | { kind: 'delim' }
  | { kind: 'response-end' };

/** Encode one pkt-line. `line` is the payload text (with its trailing newline when wanted). */
export function pktLine(line: string | Buffer): Buffer {
  const payload = typeof line === 'string' ? Buffer.from(line, 'utf8') : line;
  const length = payload.length + 4;
  const header = Buffer.from(length.toString(16).padStart(4, '0'), 'ascii');
  return Buffer.concat([header, payload]);
}

export const PKT_FLUSH = Buffer.from('0000', 'ascii');
export const PKT_DELIM = Buffer.from('0001', 'ascii');
export const PKT_RESPONSE_END = Buffer.from('0002', 'ascii');

/** Encode several lines (strings or 'flush'/'delim') into one pkt-line stream. */
export function encodePktLines(lines: ReadonlyArray<string | 'flush' | 'delim' | 'response-end'>): Buffer {
  const parts: Buffer[] = [];
  for (const line of lines) {
    if (line === 'flush') parts.push(PKT_FLUSH);
    else if (line === 'delim') parts.push(PKT_DELIM);
    else if (line === 'response-end') parts.push(PKT_RESPONSE_END);
    else parts.push(pktLine(line));
  }
  return Buffer.concat(parts);
}

/** Decode a whole buffer of pkt-lines (throws on malformed framing). */
export function decodePktLines(buffer: Buffer): GitPacket[] {
  const packets: GitPacket[] = [];
  let offset = 0;
  while (offset < buffer.length) {
    if (offset + 4 > buffer.length) throw new Error('truncated pkt-line header');
    const header = buffer.subarray(offset, offset + 4).toString('ascii');
    if (header === '0000') {
      packets.push({ kind: 'flush' });
      offset += 4;
      continue;
    }
    if (header === '0001') {
      packets.push({ kind: 'delim' });
      offset += 4;
      continue;
    }
    if (header === '0002') {
      packets.push({ kind: 'response-end' });
      offset += 4;
      continue;
    }
    const length = parseInt(header, 16);
    if (!Number.isFinite(length) || length < 4 || length > PKT_LINE_MAX) {
      throw new Error(`bad pkt-line length ${JSON.stringify(header)}`);
    }
    if (offset + length > buffer.length) throw new Error('truncated pkt-line');
    const payload = buffer.subarray(offset + 4, offset + length);
    packets.push({ kind: 'data', payload: Buffer.from(payload), raw: Buffer.from(buffer.subarray(offset, offset + length)) });
    offset += length;
  }
  return packets;
}

/** Incremental pkt-line decoder for a streaming body. */
export class PktLineDecoder {
  private buffer = Buffer.alloc(0);

  push(chunk: Buffer): void {
    this.buffer = this.buffer.length === 0 ? chunk : Buffer.concat([this.buffer, chunk]);
  }

  next(): GitPacket | null {
    if (this.buffer.length < 4) return null;
    const header = this.buffer.subarray(0, 4).toString('ascii');
    if (header === '0000') {
      this.buffer = this.buffer.subarray(4);
      return { kind: 'flush' };
    }
    if (header === '0001') {
      this.buffer = this.buffer.subarray(4);
      return { kind: 'delim' };
    }
    if (header === '0002') {
      this.buffer = this.buffer.subarray(4);
      return { kind: 'response-end' };
    }
    const length = parseInt(header, 16);
    if (!Number.isFinite(length) || length < 4 || length > PKT_LINE_MAX) {
      throw new Error(`bad pkt-line length ${JSON.stringify(header)}`);
    }
    if (this.buffer.length < length) return null;
    const payload = Buffer.from(this.buffer.subarray(4, length));
    const raw = Buffer.from(this.buffer.subarray(0, length));
    this.buffer = this.buffer.subarray(length);
    return { kind: 'data', payload, raw };
  }

  /** Bytes not yet consumed (the raw pack that follows a pkt-line command list). */
  rest(): Buffer {
    return this.buffer;
  }

  finish(): void {
    if (this.buffer.length > 0) throw new Error('trailing bytes after the pkt-line stream');
  }
}
